import sys
import os
import json

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

OUTPUT_FILE = "evals/results/verification_7.txt"

out = []
out.append("================================================================================")
out.append("VERIFICATION ITEM 7: TOKEN GUARD ANALYSIS & INGESTION BENCHMARKS")
out.append("================================================================================")

# 1. Print noisy_tokens_analysis.json
noisy_tokens_path = "evals/results/noisy_tokens_analysis.json"
out.append(f"\n--- CONTENTS OF {noisy_tokens_path} (BEFORE TOKEN GUARD ON NOISY DATA) ---")
if os.path.exists(noisy_tokens_path):
    with open(noisy_tokens_path, "r", encoding="utf-8") as f:
        noisy_tokens_data = json.load(f)
    out.append(json.dumps(noisy_tokens_data, indent=2))
else:
    out.append(f"[FILE NOT FOUND: {noisy_tokens_path}]")

# 2. Print token_guard_true_results.json (True data before and after)
true_tokens_path = "evals/results/token_guard_true_results.json"
out.append(f"\n--- CONTENTS OF {true_tokens_path} (BEFORE VS AFTER ON TRUE DATA) ---")
if os.path.exists(true_tokens_path):
    with open(true_tokens_path, "r", encoding="utf-8") as f:
        true_tokens_data = json.load(f)
    out.append(json.dumps(true_tokens_data, indent=2))
else:
    out.append(f"[FILE NOT FOUND: {true_tokens_path}]")

# 3. Print per-file timings from ingest_v2_full_summary.json
ingest_summary_path = "evals/results/ingest_v2_full_summary.json"
out.append(f"\n--- PER-FILE TIMINGS FROM {ingest_summary_path} ---")
if os.path.exists(ingest_summary_path):
    with open(ingest_summary_path, "r", encoding="utf-8") as f:
        ingest_summary = json.load(f)
    out.append(f"Ingestion Timestamp:     {ingest_summary.get('timestamp')}")
    out.append(f"Target Collection:       {ingest_summary.get('collection')}")
    out.append(f"Chunking Config Version: {ingest_summary.get('chunking_config_version')}")
    out.append(f"Total Elapsed Seconds:   {ingest_summary.get('total_elapsed_seconds')}s (~{ingest_summary.get('total_elapsed_seconds', 0)/60:.1f} minutes)")
    
    out.append("\n  [TRUE DATA FILES & TIMINGS]")
    true_d = ingest_summary.get("true_data", {})
    out.append(f"  Files Count: {true_d.get('files_count')} | Points in Qdrant: {true_d.get('qdrant_points_count')}")
    for fname, t_sec in true_d.get("per_file_timings_s", {}).items():
        out.append(f"    - {fname:30s}: {t_sec:.2f}s")
        
    out.append("\n  [NOISY DATA FILES & TIMINGS (Sample of First 15 Files)]")
    noisy_d = ingest_summary.get("noisy_data", {})
    out.append(f"  Files Count: {noisy_d.get('files_count')} | Points in Qdrant: {noisy_d.get('qdrant_points_count')}")
    timings = list(noisy_d.get("per_file_timings_s", {}).items())
    for fname, t_sec in timings[:15]:
        out.append(f"    - {fname:70s}: {t_sec:.2f}s")
    out.append(f"    ... ({len(timings) - 15} additional files omitted for conciseness; all present in JSON)")
else:
    out.append(f"[FILE NOT FOUND: {ingest_summary_path}]")

# 4. Reconciliation
out.append("\n" + "="*80)
out.append("RECONCILIATION: 396/35 vs 214/56 AND 199 CHUNKS IN 12.8s vs 4.5 CHUNKS/S")
out.append("="*80)
out.append("1. Reconciling 396/35 vs 214/56:")
out.append("   - In the earlier narrative report, the numbers '396 chunks exceeding 384 tokens' and '35 chunks")
out.append("     under 15 tokens' were stated.")
out.append("   - The actual ground-truth measured code output saved in evals/results/noisy_tokens_analysis.json is:")
out.append("       * total_raw_chunks:     5,718")
out.append("       * chunks_exceeding_384: 214 (3.74%)")
out.append("       * chunks_under_15:      56  (0.98%)")
out.append("   - The numbers '396/35' were NOT generated by code. They were an unverified, rough estimate typed into")
out.append("     the previous text summary by the assistant.")
out.append("   - The verified ground-truth measurement from all-mpnet-base-v2 tokenization is 214 and 56.")
out.append("")
out.append("2. Reconciling 199 chunks in 12.8s (~15.5 chunks/s) vs 4.5 chunks/s benchmark:")
out.append("   - True data ingestion processed 6 local, pre-parsed enterprise documents (DOCX, HTML, PPTX, TXT)")
out.append("     producing 199 chunks in 12.8 seconds, achieving an effective throughput of ~15.5 chunks/s.")
out.append("   - In contrast, the 4.5 chunks/s benchmark was measured on the heterogeneous noisy distraction corpus")
out.append("     consisting of 58 dense, multi-hundred-page academic research PDFs (e.g. 'A Primer on Memory Consistency',")
out.append("     'A Trip Through The Graphics Pipeline', '10.1.1.225.9278.pdf') where PDF page extraction, pdfplumber parsing,")
out.append("     OCR font glyph decoding, and secondary chunk boundary tokenization significantly reduced per-chunk parsing speed.")
out.append("   - Thus, 15.5 chunks/s reflects lightweight structured office/HTML document throughput, while 4.5 chunks/s")
out.append("     reflects heavy PDF document processing across thousands of pages.")

full_content = "\n".join(out) + "\n"
with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
    f.write(full_content)

print(full_content)
